// Variables
let name = "Yash";
const age = 21;

console.log(name);
console.log(age);

// Conditional Statement
let number = 10;

if (number > 5) {
    console.log("The number is greater than 5");
} else {
    console.log("The number is 5 or less");
}

// Loop
for (let i = 1; i <= 3; i++) {
    console.log(i);
}

// Function
function greet(name) {
    return "Hello, " + name + "!";
}

let greeting = greet("Yash");
console.log(greeting);
